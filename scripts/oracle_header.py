#!/usr/bin/env python3
"""Convert a vector file (docs/EXACTNESS.md) to a C oracle header.

Copyright (c) 2026 sh2o Contributors. MIT License.

Usage: python3 scripts/oracle_header.py tests/vectors/<family>.vec tests/<family>_oracle.h

The script checks the file before it writes the header: the format line, the
family line, each op line, and the byte count of each vector. It copies the
bytes without a change, so the header holds the same bytes as the file.
"""
import re
import sys

SIZES = {"i8": 1, "u8": 1, "i16": 2, "u16": 2, "i32": 4, "u32": 4}
FIELD = re.compile(r"^[a-z_][a-z0-9_]*:(%s)(?:\[([1-9][0-9]*)\])?$" % "|".join(SIZES))
SIZE_MAX = 65535  # in_size and out_size are uint16_t
OP_MAX = 256  # the op is uint8_t


def fail(path, number, text):
    sys.exit("%s:%d: %s" % (path, number, text))


def field_bytes(path, number, fields):
    total = 0
    for field in fields:
        match = FIELD.match(field)
        if not match:
            fail(path, number, "field %r is not name:type or name:type[n]" % field)
        total += SIZES[match.group(1)] * int(match.group(2) or 1)
    if total > SIZE_MAX:
        fail(path, number, "the fields have %d bytes; the maximum is %d" % (total, SIZE_MAX))
    return total


def parse(path):
    family, ops, vectors, seen_format = None, {}, [], False
    with open(path, encoding="ascii") as handle:
        for number, raw in enumerate(handle, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            words = line.split()
            if words[0] == "sh2o-vec":
                if words[1:] != ["1"]:
                    fail(path, number, "only format version 1 is known")
                seen_format = True
            elif not seen_format:
                fail(path, number, "the first line must be 'sh2o-vec 1'")
            elif words[0] == "family":
                family = words[1]
            elif words[0] == "op":
                if "in" not in words or "out" not in words or words.index("in") != 2:
                    fail(path, number, "op line is not 'op <name> in <fields> out <fields>'")
                split = words.index("out")
                name, inputs, outputs = words[1], words[3:split], words[split + 1:]
                if len(ops) == OP_MAX:
                    fail(path, number, "more than %d ops" % OP_MAX)
                ops[name] = (len(ops), field_bytes(path, number, inputs),
                             field_bytes(path, number, outputs), " ".join(words[2:]))
            elif words[0] == "v":
                if len(words) != 4 or words[1] not in ops:
                    fail(path, number, "vector line is not 'v <op> <in-hex> <out-hex>'")
                index, in_size, out_size, _ = ops[words[1]]
                data_in, data_out = bytes.fromhex(words[2]), bytes.fromhex(words[3])
                if len(data_in) != in_size or len(data_out) != out_size:
                    fail(path, number, "byte count differs from the op line")
                vectors.append((index, data_in, data_out))
            else:
                fail(path, number, "unknown line kind %r" % words[0])
    if not family or not ops or not vectors:
        fail(path, 0, "the file needs a family line, op lines and vectors")
    return family, ops, vectors


def c_bytes(data):
    return "{" + ",".join("0x%02x" % byte for byte in data) + "}"


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    family, ops, vectors = parse(argv[1])
    upper = family.upper()
    in_max = max(op[1] for op in ops.values())
    out_max = max(op[2] for op in ops.values())
    ordered = sorted(ops.items(), key=lambda item: item[1][0])
    out = [
        "/* Oracle vectors for the %s family." % family,
        " *",
        " * Copyright (c) 2026 sh2o Contributors. MIT License.",
        " * Inspired by SH2ZAM and SH4ZAM; see NOTICE.md.",
        " */",
        "/* Generated by scripts/oracle_header.py from %s. Do not edit this" % argv[1],
        " * file: change the vectors, then run make oracles. Inputs and results are",
        " * little-endian bytes, as in PS1 memory. */",
        "#ifndef SH2O_%s_ORACLE_H" % upper,
        "#define SH2O_%s_ORACLE_H" % upper,
        "#include <stdint.h>",
        "",
        "enum {",
    ]
    for name, (index, _, _, layout) in ordered:
        out.append("    %s_OP_%s=%d, /* %s */" % (upper, name.upper(), index, layout))
    out += [
        "    %s_OP_COUNT=%d" % (upper, len(ops)),
        "};",
        "",
        "#define %s_IN_MAX %d" % (upper, in_max),
        "#define %s_OUT_MAX %d" % (upper, out_max),
        "",
        "typedef struct {",
        "    uint8_t op;",
        "    uint16_t in_size,out_size;",
        "    uint8_t in[%s_IN_MAX];" % upper,
        "    uint8_t out[%s_OUT_MAX];" % upper,
        "} %s_vector_t;" % family,
        "",
        "static const char *const %s_op_names[%s_OP_COUNT]={" % (family, upper),
        "    " + ",".join('"%s"' % name for name, _ in ordered),
        "};",
        "",
        "static const %s_vector_t %s_vectors[]={" % (family, family),
    ]
    for index, data_in, data_out in vectors:
        out.append("    {%d,%d,%d,%s,%s}," % (index, len(data_in), len(data_out),
                                             c_bytes(data_in), c_bytes(data_out)))
    out += [
        "};",
        "",
        "#define %s_VECTOR_COUNT (sizeof(%s_vectors)/sizeof(%s_vectors[0]))" % (upper, family, family),
        "",
        "#endif",
    ]
    with open(argv[2], "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
