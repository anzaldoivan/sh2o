#!/bin/bash
# Manifest of the SH-2 objects: the sha256 of each object, library and model ELF
# that make cross builds in the pinned Yaul image.
# Copyright (c) 2026 sh2o Contributors. MIT License.
#
# Usage: bash scripts/sh2_manifest.sh write <image>   (make sh2-manifest runs it)
#        bash scripts/sh2_manifest.sh check <image>   (make cross runs it)
#
# Runs on the host after the build (the image has no Python and only mawk).
# write: writes tests/sh2/objects.sha256: a header comment, the line
# 'image <image>', then one sha256sum line per listed file, sorted by path.
# check: fails naming each file whose sha256 differs from the manifest, each
# listed file that is missing, each built file that is not listed, and an
# image that is not the manifest's.
#
# Listed files: build/sh2-{native,portable}/*.o, libsh2o.a and suite/*.o, and
# the model ELFs build/sh2-model{,-zam}/{native,portable}/*-model.elf. The ELFs
# link SH2ZAM's model.ld: without the SH2ZAM checkout, check skips their lines
# and write refuses.
set -eu
export LC_ALL=C

manifest=tests/sh2/objects.sha256
model_ld=external/SH2ZAM/saturn/benchmarks/integer-model/model.ld

# The built files, one path per line, sorted.
built() {
    for mode in native portable; do
        for f in build/sh2-"$mode"/*.o build/sh2-"$mode"/libsh2o.a build/sh2-"$mode"/suite/*.o; do
            [ -f "$f" ] && echo "$f"
        done
    done
    if [ "$1" = yes ]; then
        for lane in sh2-model sh2-model-zam; do
            for mode in native portable; do
                for f in build/"$lane"/"$mode"/*-model.elf; do
                    [ -f "$f" ] && echo "$f"
                done
            done
        done
    fi
    return 0
}

usage() {
    echo "usage: bash scripts/sh2_manifest.sh write|check <image>" >&2
    exit 2
}

[ $# -eq 2 ] || usage
image=$2
if [ -f "$model_ld" ]; then
    models=yes
else
    models=no
fi

case "$1" in
    write)
        if [ "$models" = no ]; then
            echo "sh2_manifest: $model_ld is absent; check out SH2ZAM (git submodule update --init external/SH2ZAM)" >&2
            exit 1
        fi
        files=$(built yes | sort)
        if [ -z "$files" ]; then
            echo "sh2_manifest: no built file; run the SH-2 build first" >&2
            exit 1
        fi
        {
            echo "# Generated by scripts/sh2_manifest.sh (make sh2-manifest); never edit by hand."
            echo "# sha256 of each SH-2 object, library and model ELF built in the image below."
            echo "image $image"
            # shellcheck disable=SC2086 # paths have no spaces
            sha256sum $files
        } > "$manifest"
        echo "sh2_manifest: wrote $manifest ($(echo "$files" | wc -l) files)"
        ;;
    check)
        [ -f "$manifest" ] || { echo "sh2_manifest: $manifest is missing" >&2; exit 1; }
        fail=0
        want_image=$(sed -n 's/^image //p' "$manifest")
        if [ "$want_image" != "$image" ]; then
            echo "sh2_manifest: image $image differs from the manifest's $want_image" >&2
            fail=1
        fi
        want=$(grep -v '^#' "$manifest" | grep -v '^image ' | sort -k2)
        if [ "$models" = no ]; then
            skipped=$(echo "$want" | grep -c ' build/sh2-model' || true)
            want=$(echo "$want" | grep -v ' build/sh2-model' || true)
            echo "sh2_manifest: $model_ld is absent; skipped $skipped model ELF line(s)"
        fi
        files=$(built "$models" | sort)
        got=""
        if [ -n "$files" ]; then
            # shellcheck disable=SC2086 # paths have no spaces
            got=$(sha256sum $files | sort -k2)
        fi
        # Each listed file: missing, or a different sha256.
        while read -r sum path; do
            [ -n "$path" ] || continue
            now=$(echo "$got" | awk -v p="$path" '$2 == p {print $1}')
            if [ -z "$now" ]; then
                echo "sh2_manifest: missing: $path" >&2
                fail=1
            elif [ "$now" != "$sum" ]; then
                echo "sh2_manifest: sha256 differs: $path" >&2
                fail=1
            fi
        done <<< "$want"
        # Each built file that the manifest does not list.
        while read -r sum path; do
            [ -n "$path" ] || continue
            if ! echo "$want" | awk -v p="$path" '$2 == p {found = 1} END {exit !found}'; then
                echo "sh2_manifest: not listed: $path" >&2
                fail=1
            fi
        done <<< "$got"
        if [ "$fail" -ne 0 ]; then
            echo "sh2_manifest: the SH-2 objects differ from $manifest; if the change is intended, run make sh2-manifest" >&2
            exit 1
        fi
        echo "sh2_manifest: ok ($(echo "$want" | grep -c . || true) files equal $manifest)"
        ;;
    *)
        usage
        ;;
esac
