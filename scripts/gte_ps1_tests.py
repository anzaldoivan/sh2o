#!/usr/bin/env python3
"""Write the ps1-tests GTE case file (tests/ps1-tests/gte_cases.txt) from two files of ps1-tests.

Copyright (c) 2026 sh2o Contributors. MIT License.

Usage: python3 scripts/gte_ps1_tests.py <ps1-tests folder> <output file>

The folder is a ps1-tests checkout (gte/test-all/tests.c, gte-fuzz/gte_valid_0xc0ffee_50.log) or a folder that holds
the two files directly. The script checks the sha256 of each file, keeps the cases with no command or with an opcode
of the model (scripts/gte_model.py MODELLED_ALL), and requires 100 cases for each of the 15 opcodes and 100 with no
command (1,600). Each case line: "<source> <cmd hex|-> <64 input words> <64 expected output words>", source "test-all" or
"gte-fuzz"; the expected output words are those of ps1-tests. tests/gte_sources_check.py reads the file.
"""
import hashlib
import re
import sys
from collections import Counter
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gte_model import MODELLED_ALL  # noqa: E402

M32 = 0xFFFFFFFF
REPOSITORY = "https://github.com/JaCzekanski/ps1-tests"
COMMIT = "3c210f4a8455931461087245eb4bc15f63916b28"
TESTS_C = "gte/test-all/tests.c"
FUZZ_LOG = "gte-fuzz/gte_valid_0xc0ffee_50.log"
SHA256 = {TESTS_C: "10136d1335069b8f8e4d5e3f1c1f197a7c4ec1e7606ece1aa658a8c0d1706240",
          FUZZ_LOG: "4577214dec452509eb5e8f3ff4c120d50bb361db13381ce9fee8bad2b3520421"}
PROVENANCE = "expected values from ps1-tests, generated by its gte-fuzz; hardware capture not stated"
PER_OP = 100
COUNT = PER_OP * (len(MODELLED_ALL) + 1)


def cmd_word(op, sf, lm, tx, vx, mx):
    """gte-fuzz/gte.h union Command: cmd 0-5, lm 10, tx 13-14, vx 15-16, mx 17-18, sf 19."""
    return op | lm << 10 | tx << 13 | vx << 15 | mx << 17 | sf << 19


def _words(block):
    w = [None] * 64
    for v, i in re.findall(r"0x([0-9a-fA-F]{1,8}),?\s*//\s*r\[(\d+)\]", block):
        w[int(i)] = int(v, 16)
    if None in w:
        raise ValueError(f"register block incomplete: {w.index(None)} missing")
    return w


def parse_tests_c(text):
    """tests.c struct test_t -> cases. opcode 0xffffffff -> cmd None; else cmd = opcode & 0x1FFFFFF (gte.s _GTE_OP)."""
    out = []
    pat = re.compile(r'\.name\s*=\s*"([^"]*)",\s*\.input\s*=\s*\{(.*?)\},\s*\.opcode\s*=\s*(0x[0-9a-fA-F]+),'
                     r'.*?\.output\s*=\s*\{(.*?)\}', re.S)
    for m in pat.finditer(text):
        op = int(m.group(3), 16)
        out.append({"source": "test-all", "cmd": None if op == M32 else op & 0x1FFFFFF,
                    "in": _words(m.group(2)), "out": _words(m.group(4))})
    return out


def parse_fuzz_log(text):
    """gte_valid_*.log -> cases: 'Test N', '> r[i] = 0x..' x64, optional 'GTE 0xNN NAME (sf=,lm=,tx=,vx=,mx=)',
    '< r[i] = 0x..' x64. No GTE line (cmd 0x40) -> cmd None."""
    out, cur = [], None
    for ln in text.splitlines():
        if ln.startswith("Test "):
            cur = {"source": "gte-fuzz", "cmd": None, "in": [None] * 64, "out": [None] * 64}
            out.append(cur)
        elif cur is not None and (m := re.match(r"([<>]) r\[(\d+)\] = 0x([0-9a-fA-F]+)", ln)):
            cur["in" if m.group(1) == ">" else "out"][int(m.group(2))] = int(m.group(3), 16)
        elif cur is not None and (m := re.match(r"GTE 0x([0-9a-fA-F]+) \S+ \(sf=(\d), lm=(\d), tx=(\d), vx=(\d), "
                                                r"mx=(\d)\)", ln)):
            cur["cmd"] = cmd_word(*(int(g, 16 if i == 0 else 10) for i, g in enumerate(m.groups())))
    for n, c in enumerate(out):
        if None in c["in"] or None in c["out"]:
            raise ValueError(f"fuzz case {n}: incomplete register dump")
    return out


def read_source(folder, rel):
    """The bytes of rel under folder (or of its file name directly in folder); the sha256 must equal SHA256[rel]."""
    path = folder / rel
    if not path.is_file():
        path = folder / Path(rel).name
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256[rel]:
        sys.exit(f"gte_ps1_tests: {path}: sha256 {digest}, expected {SHA256[rel]}")
    return data.decode("utf-8")


def header():
    return (f"# ps1-tests GTE cases for the sh2o GTE checks (written by scripts/gte_ps1_tests.py).\n"
            f"# repository {REPOSITORY}\n"
            f"# commit {COMMIT}\n"
            f"# {TESTS_C} sha256 {SHA256[TESTS_C]}\n"
            f"# {FUZZ_LOG} sha256 {SHA256[FUZZ_LOG]}\n"
            f"# provenance: {PROVENANCE}\n"
            f"# licence: MIT, see tests/ps1-tests/LICENSE\n"
            f"# count {COUNT}\n"
            f"# line: <source test-all|gte-fuzz> <cmd hex|-> <64 input words> <64 expected output words>\n")


def case_line(c):
    words = c["in"] + c["out"]
    cmd = "-" if c["cmd"] is None else format(c["cmd"], "x")
    return f"{c['source']} {cmd} " + " ".join(f"{w & M32:08x}" for w in words) + "\n"


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    folder, output = Path(argv[1]), Path(argv[2])
    cases = parse_tests_c(read_source(folder, TESTS_C)) + parse_fuzz_log(read_source(folder, FUZZ_LOG))
    cases = [c for c in cases if c["cmd"] is None or c["cmd"] & 0x3F in MODELLED_ALL]
    per = Counter(None if c["cmd"] is None else c["cmd"] & 0x3F for c in cases)
    want = {None: PER_OP, **{op: PER_OP for op in MODELLED_ALL}}
    if len(cases) != COUNT or per != want:
        sys.exit(f"gte_ps1_tests: {len(cases)} cases, expected {COUNT} ({PER_OP} for each opcode and for no command)")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header() + "".join(case_line(c) for c in cases), encoding="ascii", newline="\n")
    print(f"gte_ps1_tests: {len(cases)} cases to {output}")


if __name__ == "__main__":
    main(sys.argv)
